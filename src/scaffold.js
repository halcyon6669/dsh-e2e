/**
 * dsh-e2e — turns a scanned endpoint into a runnable case skeleton.
 *
 * The output is deliberately a *skeleton*, not a finished case. It fills in what
 * the source code actually proves:
 *
 *   - the HTTP method and path (from the annotations)
 *   - a body whose fields satisfy the validation annotations (so the request is
 *     accepted by the framework instead of failing on `@NotBlank`)
 *   - a uniqueness strategy for fields that must not collide across runs
 *
 * It does not invent the interesting part. What status to expect, which table to
 * read, what the row should contain — the source code does not say, and a
 * generator that guesses produces a case that asserts the code does whatever it
 * currently does. That is a test that can never fail, which is worse than none.
 * Those lines are emitted as TODO comments the author must resolve.
 */
import { dumpYaml } from './yaml.js'
import { sampleFor } from './scan.js'

const INDENT_NOTE = '# Generated by dsh-e2e from the project source. Fill in the TODOs:\n' +
  '#   - the expected status (and body) that proves the endpoint did its job\n' +
  '#   - the database rows that should exist afterwards, if any\n' +
  '# A case that asserts nothing it can fail on is not a test.\n' +
  '#\n' +
  '# This skeleton is the happy path (`scenario: normal`). The interesting cases are\n' +
  '# usually the others: bad input, missing auth, a conflict, a boundary. Add them as\n' +
  '# separate files with the same `endpoint` and `scenario: error`.'

function slugFor(endpoint) {
  const path = endpoint.path
    .replace(/^\//, '')
    .replace(/[^A-Za-z0-9]+/g, '-')
    .replace(/-+/g, '-')
    .replace(/-$/, '')
    .toLowerCase()
  return `${endpoint.httpMethod.toLowerCase()}-${path || 'root'}`
}

function titleFor(endpoint) {
  const method = endpoint.javaMethod || endpoint.path
  return `${endpoint.httpMethod} ${endpoint.path} — ${method}`
}

/**
 * Builds the request body object. Returns `{ body, variables, notes }`.
 *
 * A value that uses a generator (`${random.hex}`) is hoisted into
 * `request.variables` and referenced by name in the body. Two reasons:
 *
 *   - a database assertion needs to name the same value the request sent
 *     (`where username = '${username}'`), which is impossible if the generator is
 *     inlined into the body — it would generate a *second* value at assert time
 *   - the author can see, in one place, what the run will actually send
 *
 * `notes` collects everything the author has to finish, so the generated file can
 * carry them as comments next to the field they concern.
 */
function buildBody(endpoint) {
  const body = endpoint.requestBody
  if (!body) return { body: null, variables: null, notes: [] }
  if (body.fields === null) {
    return {
      body: null,
      variables: null,
      notes: [
        `request body type ${body.type} was not found in the source; add the JSON body by hand`,
      ],
    }
  }
  const out = {}
  const variables = {}
  const notes = []
  for (const field of body.fields) {
    const sample = sampleFor(field)
    if (sample.value === null) {
      if (sample.note) notes.push(sample.note)
      out[field.name] = null
      continue
    }
    if (sample.note) notes.push(sample.note)
    if (typeof sample.value === 'string' && sample.value.includes('${')) {
      // Hoist: declare the generator once, reference it from both places.
      variables[field.name] = sample.value
      out[field.name] = `\${${field.name}}`
    } else {
      out[field.name] = sample.value
    }
  }
  return {
    body: Object.keys(out).length > 0 ? out : null,
    variables: Object.keys(variables).length > 0 ? variables : null,
    notes,
  }
}

/**
 * Builds a case document for one endpoint.
 *
 * `options.target` names a registry target; without one the case cannot resolve,
 * so it is a required argument rather than a silently empty field.
 */
export function buildSkeleton(endpoint, options = {}) {
  const target = options.target ? String(options.target) : null
  if (!target) throw new Error('buildSkeleton needs options.target (a target name from the registry)')

  const { body, variables, notes } = buildBody(endpoint)
  const id = options.id ? String(options.id) : slugFor(endpoint)
  const endpointLabel = `${endpoint.httpMethod} ${endpoint.path}`

  const document = {
    id,
    // The number is assigned by the caller, which is the only place that can see
    // what is already taken (`nextCaseId` reads the case directory). Without one
    // the derived id keeps the file loadable, and `caseIdDerived` says it is not
    // the real number yet.
    ...(options.caseId ? { caseId: String(options.caseId) } : {}),
    title: titleFor(endpoint),
    description:
      `Generated skeleton for ${endpoint.controller}.${endpoint.javaMethod || '?'}` +
      ` (${endpoint.file}:${endpoint.line}).`,
    tags: ['generated', endpoint.httpMethod.toLowerCase()],
    endpoint: endpointLabel,
    // A freshly generated skeleton describes the path a user takes when nothing
    // goes wrong. The error paths are the ones worth writing next, and the panel
    // says so by counting the gap.
    scenario: options.scenario ? String(options.scenario) : 'normal',
    priority: options.priority ? String(options.priority) : 'medium',
    env: {
      target,
      ...(options.database
        ? { databases: { default: { name: String(options.database), ...(options.schema ? { schema: String(options.schema) } : {}) } } }
        : {}),
    },
    request: {
      method: endpoint.httpMethod,
      path: endpoint.path,
      ...(variables ? { variables } : {}),
      ...(body ? { json: body } : {}),
    },
    expect: {
      response: {
        status: options.expectStatus === undefined ? null : Number(options.expectStatus),
        ...(options.expectBody ? { body_contains: String(options.expectBody) } : {}),
      },
    },
  }

  // Drop the null status: a `status: null` in the file would read as "assert
  // nothing" while looking like an assertion, which is exactly the trap this
  // generator is supposed to avoid. The TODO comment carries the intent instead.
  if (document.expect.response.status === null) delete document.expect.response.status
  if (Object.keys(document.expect.response).length === 0) delete document.expect.response
  if (Object.keys(document.expect).length === 0) delete document.expect

  return { document, notes, endpoint }
}

/**
 * Renders a skeleton as YAML with the TODOs as comments.
 *
 * Written as text rather than "dump then append", because the comments have to sit
 * next to the thing they are about — a wall of TODOs at the top of the file is
 * read once and then ignored.
 */
export async function renderSkeleton(skeleton, options = {}) {
  const { document, notes, endpoint } = skeleton
  const yaml = await dumpYaml(document)
  const lines = [INDENT_NOTE, '', yaml.trimEnd()]

  const todos = []
  if (!document.expect) {
    todos.push(
      `# TODO: assert something. This endpoint returns ${endpoint.requestBody ? 'a body' : 'something'};` +
        ' add `expect.response.status` and, if it matters, `body_contains`.',
    )
  }
  if (document.env.databases) {
    const sampleVariable = document.request.variables ? Object.keys(document.request.variables)[0] : null
    todos.push(
      '# TODO: point this at the table and column the endpoint actually writes.',
      '#       Only assert state the endpoint is responsible for — a row that some other',
      '#       path also writes proves nothing about this one.',
      ...(sampleVariable
        ? [
            `#       ${sampleVariable} is already a variable, so the assertion can use it:`,
            `#         - sql: select ... from <table> where <column> = '\${${sampleVariable}}'`,
            '#           rows: [{ path: "[0].<column>", equals: "<expected>" }]',
          ]
        : [
            '#         - sql: select ... from <table> where <column> = \'...\'',
            '#           rows: [{ path: "[0].<column>", equals: "<expected>" }]',
          ]),
    )
  } else if (endpoint.requestBody) {
    todos.push(
      '# TODO: if this endpoint writes to a database, add env.databases and expect.database.',
      '#       The scan found these tables in the project but cannot know which one this',
      '#       endpoint touches: ' + (options.tables && options.tables.length ? options.tables.join(', ') : 'none'),
    )
  }
  for (const note of notes) todos.push(`# NOTE: ${note}`)

  if (todos.length > 0) {
    lines.push('', ...todos)
  }
  return `${lines.join('\n')}\n`
}

/**
 * The whole job: scan a project, pick one endpoint, emit a case file body.
 *
 * Endpoint selection is by `path` plus optional `method`; both are matched
 * case-insensitively on the method and exactly on the path after trimming a
 * trailing slash, because that is how someone reading the scan output would type
 * it.
 */
export async function generateFromSource(input = {}) {
  const { scanProject } = await import('./scan.js')
  const scan = await scanProject({
    projectPath: input.projectPath,
    maxFiles: input.maxFiles,
    maxBytes: input.maxBytes,
  })

  const wantedPath = String(input.path || '').trim()
  if (!wantedPath) {
    throw new Error('generateFromSource needs a path; call the scan first to see what exists')
  }
  const normalise = (value) => {
    const trimmed = String(value || '').trim().replace(/\/+$/, '')
    return trimmed.startsWith('/') ? trimmed : `/${trimmed}`
  }
  const wantedMethod = input.method ? String(input.method).toUpperCase() : null
  const matches = scan.endpoints.filter(
    (endpoint) =>
      normalise(endpoint.path) === normalise(wantedPath) &&
      (wantedMethod === null || endpoint.httpMethod === wantedMethod),
  )

  if (matches.length === 0) {
    const available = scan.endpoints.map((endpoint) => `${endpoint.httpMethod} ${endpoint.path}`).join(', ')
    throw new Error(
      `no endpoint matches ${wantedMethod ? `${wantedMethod} ` : ''}${wantedPath}; the scan found: ${available || 'none'}`,
    )
  }
  if (matches.length > 1) {
    const options = matches.map((endpoint) => `${endpoint.httpMethod} ${endpoint.path}`).join(', ')
    throw new Error(
      `${wantedPath} is served by more than one method (${options}); pass "method" to pick one`,
    )
  }

  const endpoint = matches[0]
  const tables = scan.entities.map((entity) => entity.table)
  const skeleton = buildSkeleton(endpoint, {
    target: input.target,
    database: input.database,
    schema: input.schema,
    id: input.id,
    caseId: input.caseId,
    scenario: input.scenario,
    priority: input.priority,
    expectStatus: input.expectStatus,
    expectBody: input.expectBody,
  })
  const yaml = await renderSkeleton(skeleton, { tables })

  return {
    yaml,
    // `id` is what the panel needs to name the file when the author saves it, and
    // it lives on the document, not on the endpoint — returning it here saves every
    // caller from re-parsing the YAML it just received.
    id: skeleton.document.id,
    caseId: skeleton.document.caseId || null,
    endpoint,
    notes: skeleton.notes,
    scan: {
      root: scan.root,
      scannedFiles: scan.scannedFiles,
      controllers: scan.controllers,
      endpoints: scan.endpoints.map((item) => ({
        httpMethod: item.httpMethod,
        path: item.path,
        controller: item.controller,
        javaMethod: item.javaMethod,
        requestBody: item.requestBody ? item.requestBody.type : null,
      })),
      entities: scan.entities,
      warnings: scan.warnings,
    },
  }
}
